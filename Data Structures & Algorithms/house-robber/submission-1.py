class Solution:
    def rob(self, nums: List[int]) -> int:
        # rob1 → הערך המקסימלי עד הבית i-2 (הבית שלפני הקודם)
        # rob2 → הערך המקסימלי עד הבית i-1 (הבית הקודם)
        #
        # בכל שלב נחליט אם לשדוד את הבית הנוכחי או לדלג עליו.
        
        rob1, rob2 = 0, 0
        
        for house in nums:
            # אם שודדים את הבית הנוכחי:
            #  הרווח = house + rob1    (כי אסור לשדוד את הבית הקודם)
            #
            # אם לא שודדים את הבית הנוכחי:
            #  הרווח = rob2            (מה שהיה הכי טוב עד הבית הקודם)
            #
            # temp = dp[i]
            temp = max(rob1 + house, rob2)
            
            # הזזה קדימה של ה"חלון" הדינאמי:
            rob1 = rob2   # rob1 הופך ל-dp[i-1]
            rob2 = temp   # rob2 הופך ל-dp[i]
        
        # rob2 הוא dp[n-1] — התשובה הסופית
        return rob2
